"""Product brief and roadmap exports (Markdown and CSV).

Labelling convention used in every export:
- **[Observed]**  copied verbatim from stored feedback
- **[Calculated]** computed deterministically from stored data
- **[Assumption]** / **[Forecast]** entered or estimated by the team — not measured
- **[AI-generated]** LLM interpretation (only if one was generated and validated)
"""

from __future__ import annotations

import io
from collections import Counter
from datetime import datetime

import pandas as pd
from sqlalchemy.orm import Session

from productpulse import APP_NAME
from productpulse.db.models import Feedback, Opportunity, RoadmapItem, Theme
from productpulse.services.prioritization import IMPACT_SCALE, RiceInputs, formula_text, score_of

_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")
MAX_LISTED_IDS = 20


def csv_safe(df: pd.DataFrame) -> pd.DataFrame:
    """Neutralise spreadsheet formula injection by prefixing risky cells with a quote."""
    out = df.copy()
    for col in out.columns:
        if out[col].dtype == object:
            out[col] = out[col].map(lambda v: "'" + v if isinstance(v, str) and v.startswith(_FORMULA_PREFIXES) else v)
    return out


def to_csv_bytes(df: pd.DataFrame) -> bytes:
    buf = io.StringIO()
    csv_safe(df).to_csv(buf, index=False)
    return buf.getvalue().encode("utf-8")


def _md_escape(text: str) -> str:
    return text.replace("\r", " ").replace("\n", " ").strip()


def _quote(fb: Feedback) -> str:
    meta = " · ".join(
        x for x in (fb.source, fb.customer_segment, fb.created_at.date().isoformat() if fb.created_at else None) if x
    )
    return f"> “{_md_escape(fb.text_original)}”\n>\n> — `{fb.id}`" + (f" ({meta})" if meta else "")


def product_brief(session: Session, opp: Opportunity, generated_at: datetime | None = None) -> str:
    generated_at = generated_at or datetime.now()
    evidence = [session.get(Feedback, e.feedback_id) for e in opp.evidence]
    evidence = [e for e in evidence if e is not None]
    theme = session.get(Theme, opp.theme_id) if opp.theme_id else None
    rice = RiceInputs(reach=opp.reach, impact=opp.impact, confidence=opp.confidence, effort=opp.effort)
    n = len(evidence)
    customers = {e.customer_id for e in evidence if e.customer_id}
    neg = sum(1 for e in evidence if e.sentiment_label == "negative")
    segs = Counter(e.customer_segment for e in evidence if e.customer_segment).most_common(3)
    areas = Counter(e.product_area for e in evidence if e.product_area).most_common(3)
    sources = Counter(e.source for e in evidence if e.source).most_common()
    quotes, seen = [], set()
    for e in sorted(evidence, key=lambda e: (e.sentiment_score if e.sentiment_score is not None else 0, e.id)):
        if e.text_hash not in seen:
            seen.add(e.text_hash)
            quotes.append(e)
        if len(quotes) >= 5:
            break

    L: list[str] = []
    L.append(f"# Product brief: {opp.name}")
    L.append("")
    L.append(
        f"*Generated by {APP_NAME} on {generated_at:%Y-%m-%d %H:%M}. Status: {opp.status}. "
        f"Owner: {opp.owner or 'unassigned'}. Target: {opp.target_release or 'not set'}.*"
    )
    L.append("")
    L.append(
        "Labels: **[Observed]** verbatim customer feedback · **[Calculated]** computed from stored data · "
        "**[Assumption]/[Forecast]** team estimates, not measured results · **[AI-generated]** model interpretation."
    )
    L.append("")

    L.append("## 1. Problem statement")
    L.append(_md_escape(opp.problem_statement) or "_Not written yet._")
    if theme and theme.ai_summary:
        L.append("")
        L.append(
            f"**[AI-generated]** ({theme.ai_provider}, citing {len(theme.ai_cited_ids or [])} records): "
            f"{_md_escape(theme.ai_summary)}"
        )
    L.append("")

    L.append("## 2. Target customer segment")
    L.append(f"- Declared segment: {opp.segment or 'not set'}; product area: {opp.product_area or 'not set'}")
    if segs:
        L.append("- **[Calculated]** Segments in the evidence: " + ", ".join(f"{s} ({c})" for s, c in segs))
    if areas:
        L.append("- **[Calculated]** Product areas in the evidence: " + ", ".join(f"{a} ({c})" for a, c in areas))
    L.append("")

    L.append("## 3. Supporting evidence")
    if n:
        L.append(
            f"- **[Calculated]** {n} linked feedback record(s)"
            + (f" from {len(customers)} distinct customer(s)" if customers else "")
            + f"; {round(100 * neg / n)}% classified negative (VADER with a product-feedback lexicon)."
        )
        if sources:
            L.append("- **[Calculated]** Sources: " + ", ".join(f"{s} ({c})" for s, c in sources))
        if theme:
            L.append(f"- Derived from theme “{theme.label}” (theme #{theme.id}, analysis run #{theme.run_id}).")
        L.append("")
        L.append("**[Observed]** Representative quotes (verbatim, with source record IDs):")
        L.append("")
        for q in quotes:
            L.append(_quote(q))
            L.append("")
        L.append(
            "Evidence IDs: "
            + ", ".join(f"`{e.id}`" for e in evidence[:MAX_LISTED_IDS])
            + (
                f" … and {n - MAX_LISTED_IDS} more (full list in the app and the feedback CSV export)"
                if n > MAX_LISTED_IDS
                else ""
            )
        )
    else:
        L.append("_No feedback records are linked. This opportunity is not yet evidence-backed._")
    L.append("")

    L.append("## 4. Proposed opportunity")
    L.append(_md_escape(opp.proposed_solution) or "_No solution proposed yet._")
    L.append("")

    L.append("## 5. Expected outcome")
    L.append(
        "**[Forecast]** If the problem is addressed, we expect fewer reports of this problem and improved "
        "sentiment among affected customers. This is a hypothesis to be validated, not a measured result."
    )
    L.append("")

    L.append("## 6. Prioritisation rationale")
    L.append(f"- **[Calculated]** RICE = {formula_text(rice)}")
    L.append(
        f"- Reach {opp.reach:g}"
        + (
            " — **[Assumption] proxy**: " + _md_escape(opp.reach_basis).removeprefix("PROXY: ")
            if opp.reach_is_proxy
            else (f" — {_md_escape(opp.reach_basis)}" if opp.reach_basis else "")
        )
    )
    L.append(f"- Impact {opp.impact:g} ({IMPACT_SCALE.get(opp.impact, '?')}) — **[Assumption]**")
    L.append(f"- Confidence {opp.confidence:.0%} — **[Assumption]**")
    L.append(f"- Effort {opp.effort:g} person-month(s) — **[Assumption]**")
    if opp.business_rationale:
        L.append(f"- Business rationale: {_md_escape(opp.business_rationale)}")
    L.append("")

    L.append("## 7. Assumptions and risks")
    risks = []
    if opp.reach_is_proxy:
        risks.append(
            "Reach is estimated from feedback volume, which over-represents vocal customers and "
            "under-represents silent ones."
        )
    if n and n < 8:
        risks.append(f"Evidence is thin ({n} records); the problem may not generalise.")
    risks.append("Sentiment is lexicon-based (VADER) and can misread sarcasm, technical language and very short text.")
    if theme:
        risks.append("Theme membership comes from unsupervised clustering and may include loosely related records.")
    risks.append("Impact, confidence and effort are team estimates.")
    L.extend(f"- {r}" for r in risks)
    L.append("")

    L.append("## 8. Success metrics")
    if n:
        L.append(
            f"- Share of negative feedback about this problem — **[Calculated] baseline** {round(100 * neg / n)}% "
            f"(n={n}); target: set by the team."
        )
    if theme and theme.trend.get("recent") is not None and theme.trend.get("status") != "insufficient_history":
        L.append(
            f"- New feedback in this theme per {theme.trend['window_days']} days — **[Calculated] baseline** "
            f"{theme.trend['recent']}; target: a sustained decrease after release."
        )
    L.append("- Adoption of the shipped solution in the target segment — baseline to be measured in product analytics.")
    L.append("")

    L.append("## 9. Open questions")
    qs = []
    if opp.reach_is_proxy:
        qs.append("What is the measured reach (accounts/users affected per quarter)?")
    if not opp.proposed_solution:
        qs.append("What solution options have been considered?")
    if not opp.owner:
        qs.append("Who owns this initiative?")
    if not opp.target_release:
        qs.append("What is the target release or timeframe?")
    if not customers and n:
        qs.append("Which customers are affected? (Feedback has no customer IDs.)")
    qs.append("Have we validated the problem with customer interviews beyond this feedback?")
    L.extend(f"- {q}" for q in qs)
    L.append("")
    return "\n".join(L)


def briefs_for(session: Session, opps: list[Opportunity]) -> str:
    return "\n\n---\n\n".join(product_brief(session, o) for o in opps)


def roadmap_markdown(session: Session, items: list[RoadmapItem]) -> str:
    L = [
        f"# Product roadmap — {datetime.now():%Y-%m-%d}",
        "",
        "_RICE scores use team-estimated inputs. Dates are targets, not commitments._",
        "",
    ]
    by_h: dict[str, list[RoadmapItem]] = {}
    for it in items:
        by_h.setdefault(it.horizon, []).append(it)
    for h, its in by_h.items():
        L.append(f"## {h}")
        for i, it in enumerate(its, 1):
            o = it.opportunity
            bits = [f"RICE {score_of(o):,.1f}", it.status, f"owner: {it.owner or '—'}"]
            if it.target_date:
                bits.append(f"target: {it.target_date.date().isoformat()}")
            bits.append(f"{len(o.evidence)} evidence records")
            L.append(f"{i}. **{o.name}** — " + " · ".join(bits))
            if it.dependencies:
                L.append(f"   - Depends on: {_md_escape(it.dependencies)}")
            if it.rationale:
                L.append(f"   - Rationale: {_md_escape(it.rationale)}")
        L.append("")
    return "\n".join(L)
