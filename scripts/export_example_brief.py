"""Generate docs/examples/* from the bundled synthetic dataset (temporary database).

    python scripts/export_example_brief.py [--backend auto|tfidf]

Creates an opportunity from the largest negative-leaning theme with illustrative,
clearly labelled assumptions, places it on the roadmap and exports the brief.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from productpulse.analysis.pipeline import run_analysis  # noqa: E402
from productpulse.config import Settings  # noqa: E402
from productpulse.db import Database  # noqa: E402
from productpulse.exports import briefs  # noqa: E402
from productpulse.services import prioritization, roadmap, themes, workspace  # noqa: E402

OUT = ROOT / "docs" / "examples"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--backend", default="auto")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as d:
        settings = Settings(database_url=f"sqlite:///{d}/example.db", embedding_backend=a.backend)
        db = Database(settings.database_url)
        with db.session() as s:
            workspace.load_sample(s, settings)
            run = run_analysis(s, settings)
        with db.session() as s:

            def neg_share(t):
                return sum(m.feedback.sentiment_label == "negative" for m in t.memberships) / len(t.memberships)

            candidates = [t for t in themes.active_themes(s) if neg_share(t) >= 0.4]
            theme = max(candidates or themes.active_themes(s), key=lambda t: len(t.memberships))
            quality = themes.insight(s, theme)["quality"].level
            data, evidence = prioritization.suggest_from_theme(s, theme, quality)
            data = data.model_copy(
                update={
                    "proposed_solution": "Illustrative: move large exports to a background job and email a download "
                    "link when ready.",
                    "business_rationale": "Illustrative: export failures appear across segments and block reporting "
                    "workflows.",
                    "impact": 2.0,
                    "effort": 3.0,
                    "owner": "Example PM",
                    "target_release": "Example: next quarter",
                }
            )
            opp = prioritization.create_opportunity(s, data, evidence, theme.id)
            roadmap.add_to_roadmap(s, [opp.id], "Now")
            header = (
                f"<!-- Generated by scripts/export_example_brief.py on {datetime.now():%Y-%m-%d} from the "
                f"synthetic sample dataset using {run.embedding_method}. Solution, impact, effort and owner "
                "are illustrative inputs, not findings. -->\n\n"
            )
            (OUT / "product_brief_example.md").write_text(header + briefs.product_brief(s, opp), encoding="utf-8")
            (OUT / "roadmap_example.md").write_text(briefs.roadmap_markdown(s, roadmap.items(s)), encoding="utf-8")
            (OUT / "roadmap_example.csv").write_bytes(
                briefs.to_csv_bytes(roadmap.board_frame(s).drop(columns=["item_id"]))
            )
            print(f"Theme: {theme.label} ({len(theme.memberships)} records, {quality})")
        db.engine.dispose()
    print(f"Wrote {OUT.relative_to(ROOT)}/product_brief_example.md, roadmap_example.md, roadmap_example.csv")


if __name__ == "__main__":
    main()
